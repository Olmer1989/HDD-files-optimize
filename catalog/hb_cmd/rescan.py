"""Команда rescan-plan: предпросмотр пересканирования выбранных папок подключённого диска (15.11.2026).

Читает только оглавление диска (пути, размеры, даты, номер файла NTFS) и прежние описи сканера; содержимое файлов
не читается, база не меняется. Само сканирование запускает владелец: окно «Диски и папки» → «Пересканировать
папку…» или сканер в консоли (команда печатается в конце ответа).
"""
from hb_core.util import out

NAMES = ('rescan-plan',)
HELP = 'что прочитает пересканирование папок подключённого диска (по оглавлению, файлы не читаются)'
GUI = False      # в окне - предпросмотр в «Пересканировать папку…» («Диски и папки», «Разбор носителя»); в командной строке есть
# для окна «Архив дисков» (раздел «Команды»); командная строка их не использует
GUI_GROUP, GUI_ORDER = 'Вопросы о диске', 20
GUI_TITLE = 'Сколько читать при пересканировании папок?'
GUI_HINT = ('Предпросмотр по оглавлению подключённого диска: сколько файлов прочитать заново (новые и изменённые),\n'
            'сколько хешей взять из прежней описи, сколько файлов исчезло. Файлы не читаются, база не меняется.\n'
            'Само сканирование - в «Диски и папки», кнопка «Пересканировать папку…».')
GUI_ARGS = {'disk': 'Диск (подключённый)', 'folder': 'Папка', 'rehash_all': 'Перечитать всё'}


def add_args(p, name):
    p.add_argument('disk')
    p.add_argument('--folder', action='append', required=True, help='папка от корня диска; можно несколько')
    p.add_argument('--rehash-all', action='store_true', help='перечитать всё, прежние хеши не брать')


def run(a):
    import service as sv                 # буква диска - по серийному номеру тома (service.volumes)
    try:
        plan = sv.rescan_plan(a.disk, a.folder, a.rehash_all)
    except sv.Refused as e:
        raise SystemExit(str(e))
    for line in plan['lines']:
        out(line)
    argv = sv.rescan_argv(a.disk, plan['letter'], plan['folders'], a.rehash_all)
    # без файлов хода и остановки окна и без --yes: в консоли сканер сам спросит подтверждение
    parts = [argv[4]] + [x for x in argv[argv.index('start'):] if x != '--yes']
    cmd = ' '.join(f'"{x}"' if ' ' in x or not x else x for x in parts)
    out('Запустить: окно «Диски и папки» → «Пересканировать папку…», или в консоли:  py ' + cmd)
